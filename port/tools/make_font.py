#!/usr/bin/env python3
"""make_font.py: the port's stand-in for the Dreamcast's ROM font, as port/runtime/font12x24.h.

    python3 port/tools/make_font.py [font.ttf]     (default: Noto Sans Mono Medium from the system's fonts)

The game draws some text (the shop's dialogue, the save file's comment) with the console's ROM font, which is part of
the BIOS and so not in the game data. The port does not use a BIOS: this renders a free font (Noto Sans Mono, SIL Open
Font License 1.1) into the ROM font's layout instead, as the game's lookup (FUN_0c2b33ec, mode 0) reads it: 12x24
glyphs of 36 bytes, 1 bit per pixel, rows running on without padding, most significant bit first; characters
0x21-0x7E at (c - 32) * 36, 0xA0-0xFF at 0xD80 + (c - 160) * 36. Needs Pillow.
"""
import os
import sys

from PIL import Image, ImageDraw, ImageFont

ROOT = os.path.normpath(os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', '..'))
OUT = os.path.join(ROOT, 'port', 'runtime', 'font12x24.h')
W, H = 12, 24
SIZE = 19             # pixels: capitals and descenders fit the 24-pixel cell


def glyph(font, ch):
    img = Image.new('L', (W, H), 0)
    d = ImageDraw.Draw(img)
    left, top, right, bottom = d.textbbox((0, 0), ch, font=font)
    ascent, descent = font.getmetrics()
    x = (W - (right - left)) // 2 - left
    y = (H - (ascent + descent)) // 2
    d.text((x, y), ch, font=font, fill=255)
    bits = [1 if img.getpixel((i, j)) >= 112 else 0 for j in range(H) for i in range(W)]
    out = bytearray(36)
    for k, b in enumerate(bits):
        if b:
            out[k // 8] |= 0x80 >> (k % 8)
    return bytes(out)


def main():
    path = sys.argv[1] if len(sys.argv) > 1 else '/usr/share/fonts/noto/NotoSansMono-Medium.ttf'
    font = ImageFont.truetype(path, SIZE)
    rows = []
    for c in list(range(0x21, 0x7F)) + list(range(0xA0, 0x100)):
        g = glyph(font, chr(c))
        rows.append('    {0x%02X, {%s}},' % (c, ', '.join('0x%02X' % b for b in g)))
    with open(OUT, 'w') as f:
        f.write('/* font12x24.h: generated by port/tools/make_font.py from Noto Sans Mono Medium. The port\'s stand-in for the\n'
                '   Dreamcast ROM font: 12x24 glyphs, 1 bit per pixel, 36 bytes each (see the script).\n\n'
                '   Noto Sans Mono: Copyright 2022 The Noto Project Authors (https://github.com/notofonts/latin-greek-cyrillic).\n'
                '   Licensed under the SIL Open Font License, Version 1.1 (https://openfontlicense.org). */\n\n'
                'static const struct { unsigned char c; unsigned char bits[36]; } font12x24[] = {\n')
        f.write('\n'.join(rows))
        f.write('\n};\n')
    print('%s: %d glyphs' % (os.path.relpath(OUT, ROOT), len(rows)))


if __name__ == '__main__':
    main()
